#!/usr/bin/env python3
"""Research Red: dialogue portrait table and Pokemon portraits.

Reads graphics/research_red/portraits.txt and
  * builds graphics/research_red/pokemon/<name>/portrait.png for each Pokemon
    speaker: the first frame of graphics/pokemon/<name>/anim_front.png with a
    white "cut-out" outline (or pokemon_handmade/<name>.png if it exists)
  * writes src/data/research_red/portraits.h (graphics + speaker table) for
    src/rr_portrait.c

Usage: python3 tools/research_red/build_portraits.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rrpng  # noqa: E402
from png_indexed import load_indexed  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GFX = os.path.join(REPO, "graphics/research_red")
CONFIG = os.path.join(GFX, "portraits.txt")
HEADER = os.path.join(REPO, "src/data/research_red/portraits.h")
COLORS = ["orange", "green", "blue", "brown", "pink", "purple", "teal", "red", "gray"]


def parse():
    speakers = []
    for n, line in enumerate(open(CONFIG), 1):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cols = [c.strip() for c in line.split("|")]
        if len(cols) not in (3, 5) or cols[2] not in COLORS:
            sys.exit(f"portraits.txt:{n}: expected 'Speaker | folder | color [| alt folder | FLAG]'")
        speakers.append({"name": cols[0], "folder": cols[1], "color": cols[2],
                         "alt": cols[3] if len(cols) == 5 else None,
                         "flag": cols[4] if len(cols) == 5 else None})
    return speakers


def build_pokemon(name):
    """64x64 portrait from the species' front sprite, outlined in white."""
    hand = os.path.join(GFX, "pokemon_handmade", name + ".png")
    out_dir = os.path.join(GFX, "pokemon", name)
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, "portrait.png")
    if os.path.exists(hand):
        w, h, rows, pal = load_indexed(hand)
    else:
        w, h, rows, pal = load_indexed(os.path.join(REPO, "graphics/pokemon", name, "anim_front.png"))
        rows = [r[:64] for r in rows[:64]]
        white = max(range(1, len(pal)), key=lambda i: sum(pal[i]))
        solid = [[i != 0 for i in r] for r in rows]
        for y in range(64):
            for x in range(64):
                if solid[y][x]:
                    continue
                if any(0 <= y + dy < 64 and 0 <= x + dx < 64 and solid[y + dy][x + dx]
                       for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1))):
                    rows[y][x] = white
    pal = (list(pal) + [(0, 0, 0)] * 16)[:16]
    rrpng.write_png_indexed4(out, 64, 64, [r[:64] for r in rows[:64]], pal)


def ident(folder):
    return folder.replace("/", "_")


def main():
    speakers = parse()
    folders = []
    for s in speakers:
        for f in (s["folder"], s["alt"]):
            if f and f not in folders:
                folders.append(f)
    for f in folders:
        if f.startswith("pokemon/"):
            build_pokemon(f.split("/", 1)[1])
        elif not os.path.exists(os.path.join(GFX, f, "portrait.png")):
            sys.exit(f"missing {os.path.join('graphics/research_red', f, 'portrait.png')}")

    lines = ["// Generated by tools/research_red/build_portraits.py from",
             "// graphics/research_red/portraits.txt. Do not edit by hand.", ""]
    for f in folders + ["cast/player_m", "cast/player_f"]:
        lines.append(f'static const u32 sPortraitGfx_{ident(f)}[] = INCBIN_U32("graphics/research_red/{f}/portrait.4bpp");')
        lines.append(f'static const u16 sPortraitPal_{ident(f)}[] = INCBIN_U16("graphics/research_red/{f}/portrait.gbapal");')
    # #5/#95: the full-body look (64x64 battle.png) for people, behind the
    # banter look switch (FLAG_RR_BANTER_FULL_BODY); Pokémon keep their portrait
    def full(f):
        return f and os.path.exists(os.path.join(GFX, f, "battle.png"))
    for f in folders + ["cast/player_m", "cast/player_f"]:
        if full(f):
            lines.append(f'static const u32 sFullBodyGfx_{ident(f)}[] = INCBIN_U32("graphics/research_red/{f}/battle.4bpp");')
            lines.append(f'static const u16 sFullBodyPal_{ident(f)}[] = INCBIN_U16("graphics/research_red/{f}/battle.gbapal");')
    lines.append("")
    for i, s in enumerate(speakers):
        lines.append(f'static const u8 sSpeakerName_{i}[] = _("{s["name"]}");')
    lines += ["", "static const struct RRSpeaker sSpeakers[] =", "{"]
    for i, s in enumerate(speakers):
        alt = f'sPortraitGfx_{ident(s["alt"])}, sPortraitPal_{ident(s["alt"])}, {s["flag"]}' if s["alt"] else "NULL, NULL, 0"
        body = f'sFullBodyGfx_{ident(s["folder"])}, sFullBodyPal_{ident(s["folder"])}' if full(s["folder"]) else "NULL, NULL"
        altbody = f'sFullBodyGfx_{ident(s["alt"])}, sFullBodyPal_{ident(s["alt"])}' if full(s["alt"]) else "NULL, NULL"
        lines.append(f'    {{ sSpeakerName_{i}, sPortraitGfx_{ident(s["folder"])}, sPortraitPal_{ident(s["folder"])}, '
                     f'RR_NAME_{s["color"].upper()}, {alt}, {body}, {altbody} }},')
    lines += ["};", ""]
    os.makedirs(os.path.dirname(HEADER), exist_ok=True)
    open(HEADER, "w").write("\n".join(lines))
    print(f"{len(speakers)} speakers, {len(folders)} portraits -> {os.path.relpath(HEADER, REPO)}")


if __name__ == "__main__":
    main()
