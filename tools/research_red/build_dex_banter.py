#!/usr/bin/env python3
"""Research Red: Pokédex banter lines -> src/data/research_red/dex_banter.h

Reads data/research_red/dex_banter.txt (see the notes at its top), wraps each
line to the 34-character text box and writes the table src/rr_dex_banter.c
plays from.

Usage: python3 tools/research_red/build_dex_banter.py [--check]
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "data/research_red/dex_banter.txt")
OUT = os.path.join(REPO, "src/data/research_red/dex_banter.h")
SPECIES_H = os.path.join(REPO, "include/constants/species.h")
WIDTH = 34
# placeholder -> (game code, width used for wrapping)
PLACEHOLDERS = {"{PLAYER}": ("{PLAYER}", 7), "{SPECIES}": ("{STR_VAR_3}", 10), "{STARTER}": ("{STR_VAR_2}", 10)}
SPECIAL = {"DEFAULT", "ELM FAMILY", "JENNY FAMILY"}


def species_constant(name, known):
    c = "SPECIES_" + re.sub(r"[^A-Z0-9]+", "_", name.upper().replace("♂", " M").replace("♀", " F")
                              .replace("'", "").replace(".", "")).strip("_")
    if c not in known:
        sys.exit(f"dex_banter.txt: unknown Pokémon '{name}' (looked for {c})")
    return c


def visible_len(word):
    n = len(word)
    for ph, (_, w) in PLACEHOLDERS.items():
        n += word.count(ph) * (w - len(ph))
    return n


def wrap(line):
    """Speaker prefix + text -> rows of at most WIDTH characters."""
    rows, row = [], ""
    for word in line.split():
        cand = (row + " " + word) if row else word
        if visible_len(cand) > WIDTH and row:
            rows.append(row)
            row = word
        else:
            row = cand
    rows.append(row)
    out = rows[0]
    for i, r in enumerate(rows[1:]):
        out += ("\\n" if i == 0 else "\\l") + r
    for ph, (code, _) in PLACEHOLDERS.items():
        out = out.replace(ph, code)
    # the game's charmap has curly quotes, not straight ones
    parts = out.split('"')
    return "".join(p + ("“" if i % 2 == 0 else "”") for i, p in enumerate(parts[:-1])) + parts[-1]


def parse():
    blocks, order, current = {}, [], None
    for n, raw in enumerate(open(SRC, encoding="utf-8"), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            current = line[1:-1].strip()
            if current in blocks:
                sys.exit(f"dex_banter.txt:{n}: [{current}] appears twice")
            blocks[current] = []
            order.append(current)
            continue
        m = re.match(r"(Ivy|P)\s*:\s*(.+)$", line)
        if not m or current is None:
            sys.exit(f"dex_banter.txt:{n}: expected 'Ivy: ...' or 'P: ...' under a [Species] heading")
        speaker = "Ivy" if m.group(1) == "Ivy" else "{PLAYER}"
        blocks[current].append(wrap(f"{speaker}: {m.group(2)}"))
    return blocks, order


def emit_lines(name, lines):
    out = []
    for i, text in enumerate(lines):
        out.append(f'static const u8 {name}_{i}[] = _("{text}");')
    out.append(f"static const u8 *const {name}[] = {{ " + ", ".join(f"{name}_{i}" for i in range(len(lines))) + ", NULL };")
    return out


def main():
    known = set(re.findall(r"\b(SPECIES_\w+)\s*=", open(SPECIES_H).read()))
    blocks, order = parse()
    for s in SPECIAL:
        if s not in blocks:
            sys.exit(f"dex_banter.txt: missing [{s}]")
    if len(blocks["DEFAULT"]) % 2:
        sys.exit("dex_banter.txt: [DEFAULT] needs lines in pairs")
    lines = ["// Generated by tools/research_red/build_dex_banter.py from",
             "// data/research_red/dex_banter.txt. Do not edit by hand.", ""]
    lines += emit_lines("sDexBanter_Default", blocks["DEFAULT"])
    lines += emit_lines("sDexBanter_ElmFamily", blocks["ELM FAMILY"])
    lines += emit_lines("sDexBanter_JennyFamily", blocks["JENNY FAMILY"])
    table = []
    for name in order:
        if name in SPECIAL:
            continue
        const = species_constant(name, known)
        ident = "sDexBanter_" + const[len("SPECIES_"):].title().replace("_", "")
        lines += emit_lines(ident, blocks[name])
        table.append((const, ident))
    lines += ["", "static const struct RRDexBanter sDexBanterTable[] =", "{"]
    lines += [f"    {{ {c}, {i} }}," for c, i in table]
    lines += ["};", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != text:
            sys.exit("dex_banter.h is out of date: run tools/research_red/build_dex_banter.py")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"{len(table)} species, {sum(len(v) for v in blocks.values())} lines -> {os.path.relpath(OUT, REPO)}")


if __name__ == "__main__":
    main()
